"""Creates the demo data set: 2 teachers, 6 students, 5 subjects, marks, statuses."""
from database import db
from security import hash_password

# Mirrors the marks the old front-end-only version generated, so the demo
# report cards come out identical after the move to a real backend.
SUBJECTS = [
    ("SUB1", "Data Structures", 100, "T1", "submitted"),
    ("SUB2", "Database Systems", 100, "T2", "approved"),
    ("SUB3", "Web Technologies", 100, "T1", "approved"),
    ("SUB4", "Operating Systems", 100, "T2", "approved"),
    ("SUB5", "Software Engineering", 100, "T1", "draft"),
]

STUDENTS = [
    ("S101", "CS101", "Aarav Sharma", "BCA-3A", "2003-01-10"),
    ("S102", "CS102", "Diya Verma", "BCA-3A", "2003-02-11"),
    ("S103", "CS103", "Rohan Gupta", "BCA-3A", "2003-03-12"),
    ("S104", "CS104", "Ishita Singh", "BCA-3A", "2003-04-13"),
    ("S105", "CS105", "Kabir Malik", "BCA-3A", "2003-05-14"),
    ("S106", "CS106", "Meera Nair", "BCA-3A", "2003-06-15"),
]

TEACHERS = [("T1", "Dr. Anita Rao"), ("T2", "Prof. Vikram Desai")]

# Marks that used to be generated by (i * 37 + j * 23) % 43 + 50
FORCED_MARKS = {("S104", "SUB3"): 32}


def generated_marks():
    marks = {}
    for i, (sid, *_rest) in enumerate(STUDENTS):
        for j, (bid, *_b) in enumerate(SUBJECTS):
            marks[(sid, bid)] = (i * 37 + j * 23) % 43 + 50
    marks.update(FORCED_MARKS)
    return marks


def seed_if_empty():
    with db() as conn:
        empty = conn.execute("SELECT COUNT(*) AS n FROM students").fetchone()["n"] == 0
        if not empty:
            return False

        conn.execute(
            "INSERT INTO admins (id, name, password_hash) VALUES (?,?,?)",
            ("admin", "Administrator", hash_password("admin123")),
        )
        conn.executemany(
            "INSERT INTO teachers (id, name, password_hash) VALUES (?,?,?)",
            [(tid, name, hash_password("teach123")) for tid, name in TEACHERS],
        )
        conn.executemany(
            "INSERT INTO students (id, roll, name, cls, dob, password_hash)"
            " VALUES (?,?,?,?,?,?)",
            [
                (sid, roll, name, cls, dob, hash_password("stud123"))
                for sid, roll, name, cls, dob in STUDENTS
            ],
        )
        conn.executemany(
            "INSERT INTO subjects (id, name, max_marks, teacher_id) VALUES (?,?,?,?)",
            [(bid, name, mx, tid) for bid, name, mx, tid, _st in SUBJECTS],
        )
        conn.executemany(
            "INSERT INTO result_status (subject_id, status) VALUES (?,?)",
            [(bid, st) for bid, _n, _m, _t, st in SUBJECTS],
        )
        conn.executemany(
            "INSERT INTO marks (student_id, subject_id, marks) VALUES (?,?,?)",
            [(sid, bid, m) for (sid, bid), m in generated_marks().items()],
        )
        return True